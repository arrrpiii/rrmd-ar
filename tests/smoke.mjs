import {chromium} from '@playwright/test';
import fs from 'node:fs/promises';
const browser=await chromium.launch({headless:true,executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1440,height:1000},acceptDownloads:true});
const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')console.log('BROWSER',m.text().slice(0,400));});
await page.goto('http://127.0.0.1:3002/',{waitUntil:'networkidle'});
await page.getByLabel('Upload portrait').setInputFiles('tests/fixtures/portrait.jpg');
await page.getByText('Face detected',{exact:true}).waitFor({timeout:60000});
console.log('PASS face detected');
await page.getByLabel('Upload jewellery model').setInputFiles('../RDLR851.3dm');
await page.getByRole('button',{name:/Preview placement/}).waitFor({timeout:60000});
await page.waitForFunction(()=>!document.querySelector('button.primary')?.disabled,{timeout:60000});
await page.getByRole('button',{name:/Preview placement/}).click();
await page.getByAltText('Generated jewellery try-on').waitFor({timeout:60000});
console.log('PASS first CAD image generated');
await page.screenshot({path:'test-results/first-model.png',fullPage:true});
const [download]=await Promise.all([page.waitForEvent('download'),page.getByRole('link',{name:'Download PNG'}).click()]);await download.saveAs('test-results/try-on.png');
console.log('DOWNLOAD',await fs.stat('test-results/try-on.png').then(x=>x.size));
console.log('ERRORS',errors);
await browser.close();
