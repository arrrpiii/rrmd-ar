import { chromium, expect } from '@playwright/test';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const base=process.env.TRYON_URL||'http://127.0.0.1:3002';
const api='http://127.0.0.1:8765';
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_PATH||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1440,height:1000},acceptDownloads:true});
const errors=[],requests=[],checks=[];let jobId;
page.on('pageerror',error=>errors.push(error.message));
page.on('request',request=>requests.push(request.url()));
page.on('response',async response=>{if(response.url()===api+'/jobs'&&response.status()===202)jobId=(await response.json()).id;});
const pass=name=>{checks.push(name);console.log('PASS',name);};
try {
 await page.goto(base,{waitUntil:'networkidle'});
 await expect(page.getByText('FLUX.2 Klein · running on your Mac',{exact:true})).toBeVisible();
 await expect(page.getByRole('button',{name:'Generate natural try-on',exact:true})).toBeDisabled();
 pass('Local model detected; generation requires inputs and placement');
 await page.getByLabel('Upload portrait').setInputFiles('tests/fixtures/portrait.jpg');
 await expect(page.getByText('Face detected',{exact:true})).toBeVisible({timeout:60000});
 await page.getByLabel('Upload jewellery model').setInputFiles('../RDLR851.3dm');
 await expect(page.locator('button.primary')).toBeEnabled({timeout:60000});
 await page.locator('button.primary').click();
 await expect(page.getByAltText('Generated jewellery try-on')).toBeVisible();
 await page.getByLabel('Size',{exact:true}).fill('8');
 await page.getByLabel('Horizontal position',{exact:true}).fill('35');
 await page.getByLabel('Vertical position',{exact:true}).fill('21');
 await page.getByRole('button',{name:'Image right',exact:true}).click();
 await page.getByLabel('Horizontal position',{exact:true}).fill('63');
 await page.getByLabel('Vertical position',{exact:true}).fill('21');
 await page.getByRole('button',{name:'Generate natural try-on',exact:true}).click();
 await expect(page.getByRole('button',{name:'Cancel generation',exact:true})).toBeVisible({timeout:15000});
 await expect(page.getByLabel('Size',{exact:true})).toBeDisabled();
 pass('Real CAD reference, photo and placement submitted; controls locked during generation');
 await expect(page.getByAltText('Locally generated natural jewellery try-on')).toBeVisible({timeout:240000});
 assert.ok(jobId);
 const job=await fetch(api+'/jobs/'+jobId).then(r=>r.json());
 assert.equal(job.state,'succeeded');
 pass(`Actual offline MLX generation completed in ${job.elapsed}s; ${job.progress.peak_memory_gb} GB peak MLX memory`);
 const [download]=await Promise.all([page.waitForEvent('download'),page.getByRole('link',{name:'Download PNG'}).click()]);
 await download.saveAs('test-results/local-ai-try-on.png');
 const bytes=await fs.readFile('test-results/local-ai-try-on.png');
 assert.equal(bytes.subarray(1,4).toString(),'PNG');
 const backend=Buffer.from(await fetch(api+'/jobs/'+jobId+'/result').then(r=>r.arrayBuffer()));
 assert.ok(backend.equals(bytes));
 pass('Displayed and downloaded PNG comes from the model output');
 await page.screenshot({path:'test-results/local-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'test-results/local-mobile.png',fullPage:true});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 pass('Mobile layout fits viewport');
 await page.getByLabel('Size',{exact:true}).fill('9');
 await expect(page.getByAltText('Locally generated natural jewellery try-on')).toHaveCount(0);
 await expect(page.getByRole('link',{name:'Download PNG'})).toHaveCount(0);
 pass('Changing fit clears stale AI result');
 assert.deepEqual(errors,[]);
 assert.deepEqual(requests.filter(url=>!url.startsWith(base)&&!url.startsWith(api)&&!url.startsWith('blob:')&&!url.startsWith('data:')),[]);
 pass('No browser errors or third-party requests');
 await fs.writeFile('test-results/local-report.json',JSON.stringify({jobId,job,checks},null,2));
} finally {await browser.close();}
