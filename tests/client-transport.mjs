const {outputText}=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}});
const client=await import('data:text/javascript;base64,'+Buffer.from(outputText).toString('base64'));
const calls=[];
globalThis.fetch=async (url,init)=>{calls.push({url,init});return new Response(JSON.stringify({model_ready:true,id:'test'}),{status:200});};
globalThis.window={location:{hostname:'127.0.0.1'}};
await client.localStatus();
assert.equal(calls.pop().url,'http://127.0.0.1:8765/status');
window.location.hostname='shop.example.com';
